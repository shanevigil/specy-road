    "    reclaim W | reconcile W | open W | adopt --node ID --harness H --session SID | hook --format H\n"
    "    — launch a claimed leaf on a harness and return at once; sync at the start of every\n"
    "    turn; handoff/reclaim lease a worker to a human (see docs/orchestration-workers.md)\n"
    "  orchestrate plan [PARENT] — per ready leaf, which roster model should coordinate,\n"
    "    execute, and review, from sensitivity, eligibility, availability, cost and\n"
    "    profile scores; exit 1 when a leaf cannot be staffed (optional: --json --today)\n"
    "  models list|show <ID>|stale — the roster with profiles and role scores; one profile;\n"
    "    profiles whose research is old or superseded (exit 1 if a rostered one is)\n"
