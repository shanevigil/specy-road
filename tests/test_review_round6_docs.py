def test_refresh_with_two_packs_keeps_the_shared_skills_for_the_second_pack(tmp_path: Path) -> None:
    """Gemini: a pre-0.3.0 manifest with two packs; the first writes the skills, the second must not disown them."""
    manifest = tmp_path / ".specyrd" / "manifest.json"
    manifest.parent.mkdir()
    manifest.write_text(json.dumps({"specyrd_version": "0.2.3", "role": "dev", "project_root": ".", "agents": {
        "claude-code": [".claude/commands/specyrd-validate.md", ".specyrd/README.md"],
        "cursor": [".cursor/commands/specyrd-validate.md", ".specyrd/README.md"]}}), encoding="utf-8")
    written, _ = refresh_stubs(tmp_path)
    assert not [w for w in written if "skipped" in w]
    agents = _manifest(tmp_path)["agents"]
    assert str(SKILL) in agents["cursor"] and str(SKILL) in agents["claude-code"]
    assert str(LINK) in agents["claude-code"] and (tmp_path / LINK).is_symlink()
