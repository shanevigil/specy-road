# --- F17: the bootstrap prompt merges the block and still names everything in it --

def test_bootstrap_prompt_merges_the_block_verbatim_and_names_every_command_and_env_var() -> None:
    block = BLOCK.read_text(encoding="utf-8")
    prompt = PROMPT.read_text(encoding="utf-8")
    assert "Merge the managed block verbatim" in prompt and "refresh-stubs" in prompt
    commands = set(re.findall(r"`specy-road ([a-z][a-z-]+)", block))
    env_vars = set(re.findall(r"\bSPECY_ROAD_[A-Z_]+", block))
    assert commands and env_vars
    missing = [c for c in sorted(commands) if f"specy-road {c}" not in prompt and f"`{c}" not in prompt]
    missing += [v for v in sorted(env_vars) if v not in prompt]
    assert not missing, missing


# --- F15 (e): the five skill descriptions route narrowly --------------------------

def _description(name: str) -> str:
    text = (COMMANDS / f"specyrd-{name}.md").read_text(encoding="utf-8")
    return re.search(r'^description: "(.*)"$', text, re.M).group(1)


def test_skill_descriptions_state_their_limits() -> None:
    assert "claims nothing" in _description("brief")
    assert "switches branches" in _description("sync")
    assert "not indexed" in _description("search")
    assert "--force overwrites" in _description("constitution")
    assert "require_implementation_review_before_finish" in _description("finish")


