"""One skill file per command, read by every harness (slices note, decision D)."""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from specy_road import __version__
from specy_road.bundled_scripts.refresh_stubs import refresh_stubs
from specy_road.specyrd_init import run_init
from specy_road.specyrd_skills import SKILL_AGENTS, link_target, with_name

SKILL = Path(".agents/skills/specyrd-validate/SKILL.md")
LINK = Path(".claude/skills/specyrd-validate")


def _init(tmp_path: Path, agent: str, **kw):
    return run_init(target=tmp_path, agent=agent, dry_run=False, force=False, ai_commands_dir=None, **kw)


def _manifest(root: Path) -> dict:
    return json.loads((root / ".specyrd" / "manifest.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("agent", sorted(SKILL_AGENTS))
def test_every_skill_pack_writes_the_same_file(tmp_path: Path, agent: str) -> None:
    r = _init(tmp_path, agent, role="dev")
    assert str(SKILL) in r.written
    text = (tmp_path / SKILL).read_text(encoding="utf-8")
    assert text.startswith("---\nname: specyrd-validate\ndescription: ")
    assert f"Generated by specyrd {__version__}." in text
    assert str(SKILL) in _manifest(tmp_path)["agents"][agent]


def test_claude_code_links_each_skill_to_the_shared_file(tmp_path: Path) -> None:
    r = _init(tmp_path, "claude-code", role="dev")
    link = tmp_path / LINK
    assert link.is_symlink()
    assert os.readlink(link) == link_target("claude-code", "specyrd-validate.md") == "../../.agents/skills/specyrd-validate"
    assert (link / "SKILL.md").resolve() == (tmp_path / SKILL).resolve()
    assert f"{LINK} (created)" in r.written
    assert str(LINK) in _manifest(tmp_path)["agents"]["claude-code"]


@pytest.mark.parametrize("agent", ["cursor", "codex"])
def test_native_readers_get_no_links(tmp_path: Path, agent: str) -> None:
    _init(tmp_path, agent, role="dev")
    assert not (tmp_path / ".claude").exists() and not (tmp_path / ".cursor" / "commands").exists()


def test_two_packs_share_one_skill_file(tmp_path: Path) -> None:
    _init(tmp_path, "cursor", role="dev")
    first = (tmp_path / SKILL).read_text(encoding="utf-8")
    r = _init(tmp_path, "claude-code", role="dev")
    assert str(SKILL) in r.skipped and (tmp_path / SKILL).read_text(encoding="utf-8") == first
    assert (tmp_path / LINK).is_symlink()
    agents = _manifest(tmp_path)["agents"]
    assert str(SKILL) in agents["cursor"] and str(SKILL) in agents["claude-code"]


def test_a_wrong_link_is_repaired(tmp_path: Path) -> None:
    _init(tmp_path, "claude-code", role="dev")
    link = tmp_path / LINK
    link.unlink()
    os.symlink("../../somewhere-else", link)
    written, _ = refresh_stubs(tmp_path)
    assert f"{LINK} (updated)" in written
    assert os.readlink(link) == "../../.agents/skills/specyrd-validate"
    written, _ = refresh_stubs(tmp_path)
    assert written == []


def test_refresh_migrates_a_pre_skills_install_and_names_the_old_stubs(tmp_path: Path, capsys) -> None:
    from specy_road.bundled_scripts.refresh_stubs import _report

    commands = tmp_path / ".claude" / "commands"
    commands.mkdir(parents=True)
    (commands / "specyrd-validate.md").write_text("old stub\n", encoding="utf-8")
    manifest = tmp_path / ".specyrd" / "manifest.json"
    manifest.parent.mkdir(parents=True)
    manifest.write_text(json.dumps({"specyrd_version": "0.2.3", "role": "dev", "project_root": ".",
                                    "agents": {"claude-code": [".claude/commands/specyrd-validate.md", ".specyrd/README.md"]}}))
    written, orphans = refresh_stubs(tmp_path)
    assert str(SKILL) in written and f"{LINK} (created)" in written
    assert orphans == [".claude/commands/specyrd-validate.md"]
    assert (commands / "specyrd-validate.md").read_text(encoding="utf-8") == "old stub\n"
    _report(written, orphans, dry_run=False)
    out = capsys.readouterr().out
    assert "pre-0.3.0 command stubs" in out and "rm .claude/commands/specyrd-validate.md" in out


def test_generic_pack_is_unchanged(tmp_path: Path) -> None:
    r = run_init(target=tmp_path, agent="generic", dry_run=False, force=False,
                 ai_commands_dir=Path("docs/agent-cmds"), role="dev")
    assert "docs/agent-cmds/specyrd-validate.md" in r.written
    text = (tmp_path / "docs" / "agent-cmds" / "specyrd-validate.md").read_text(encoding="utf-8")
    assert not text.startswith("---\nname:")
    assert not (tmp_path / ".agents").exists()


def test_with_name_handles_a_stub_without_frontmatter() -> None:
    assert with_name("x", "body\n") == "---\nname: x\n---\n\nbody\n"
    assert with_name("x", "---\ndescription: d\n---\nbody\n") == "---\nname: x\ndescription: d\n---\nbody\n"


def test_symlink_failure_falls_back_to_a_copy(tmp_path: Path, monkeypatch) -> None:
    def refuse(*_a, **_k):
        raise OSError("symlinks need a privilege here")

    monkeypatch.setattr("specy_road.specyrd_skills.os.symlink", refuse)
    r = _init(tmp_path, "claude-code", role="dev")
    assert f"{LINK} (copied)" in r.written
    copy = tmp_path / LINK / "SKILL.md"
    assert copy.is_file() and not (tmp_path / LINK).is_symlink()
    assert copy.read_text(encoding="utf-8") == (tmp_path / SKILL).read_text(encoding="utf-8")
